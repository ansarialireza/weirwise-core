def get_jina_token_from_secrets() -> str:
    """Safely retrieves Jina token from test-secrets without exposing it in logs."""
    secrets_path = r"C:\Users\Alireza\GitHub\test-secrets\.env.testing"
    if not os.path.exists(secrets_path):
        pytest.skip(f"Secrets file not found at {secrets_path}")

    token = None
    with open(secrets_path, "r", encoding="utf-8") as f:
        for line in f:
            stripped = line.strip()
            if stripped.startswith("jina_"):
                token = stripped
                break

    if not token:
        pytest.skip("No Jina AI token found in test-secrets/.env.testing")
    return token


async def test_jina_real_api_embedding_request():
    """1-4: Verify live Jina AI embedding request produces finite, 1536-dim vectors."""
    token = get_jina_token_from_secrets()
    assert token is not None, "Jina token must be present"

    # Use Jina AI v1 endpoint with jina-embeddings-v4 configured for 1536 dimensions
    settings = Settings(
        embedding_base_url="https://api.jina.ai/v1",
        embedding_api_key=token,
        embedding_model="jina-embeddings-v4",
        embedding_dimensions=1536,
        embedding_timeout_seconds=30.0,
    )
    provider = OpenAIEmbeddingProvider(settings)

    # 1. Ensure provider does not fall back to SHA-256
    # When api_key is present, provider makes real HTTP request
    assert provider.api_key is not None

    # 2. Make real controlled API request with short, harmless string
    test_texts = [
        "Weirwise AI infrastructure provides resilient retrieval-augmented generation.",
        "pgvector performs cosine similarity operations directly within PostgreSQL.",
    ]
    embeddings = await provider.get_embeddings(test_texts)

    # 3. Confirm nonempty, finite numeric vectors
    assert len(embeddings) == 2, "Must return exactly 2 embedding vectors"
    for vec in embeddings:
        assert len(vec) == 1536, f"Expected 1536 dimensions, got {len(vec)}"
        assert all(isinstance(val, float) for val in vec), "All vector components must be floats"
        assert not any(np.isnan(vec)), "Vector contains NaN values"
        assert not any(np.isinf(vec)), "Vector contains infinite values"
        norm = np.linalg.norm(vec)
        assert norm > 0.0, "Vector norm must be strictly positive"


async def test_jina_embeddings_pgvector_storage_and_semantic_search():
    """5-7: Ingest and query vectors generated by real Jina AI and verify pgvector search."""
    token = get_jina_token_from_secrets()

    # Ensure pgvector extension in test DB
    async with engine.begin() as conn:
        await conn.execute(text("CREATE EXTENSION IF NOT EXISTS vector"))

    raw_key, key_hash = generate_api_key(prefix="ww_jina_test_")
    tenant_name = f"Jina-Test-Tenant-{uuid4().hex[:8]}"

    # Provision isolated test tenant in PostgreSQL
    async with AsyncSessionLocal() as session:
        tenant = Tenant(name=tenant_name)
        session.add(tenant)
        await session.flush()
        api_key_rec = APIKey(tenant_id=tenant.id, key_hash=key_hash, name="Jina Test Key")
        session.add(api_key_rec)
        await session.commit()
        tenant_id = tenant.id

    headers = {"X-API-Key": raw_key}

    # Override app dependency settings for Jina provider with 1536 dimensions
    from server.app.config import get_settings

    def get_jina_test_settings():
        return Settings(
            embedding_base_url="https://api.jina.ai/v1",
            embedding_api_key=token,
            embedding_model="jina-embeddings-v4",
            embedding_dimensions=1536,
            ingestion_mode="inline",
        )

    app.dependency_overrides[get_settings] = get_jina_test_settings

    try:
        transport = ASGITransport(app=app)
        async with AsyncClient(transport=transport, base_url="http://test") as client:
            # 1. Create Knowledge Base
            kb_res = await client.post(
                "/api/v1/knowledge-bases",
                json={"name": "Jina KB", "description": "KB using Jina AI embeddings"},
                headers=headers,
            )
            assert kb_res.status_code == 201
            kb_id = kb_res.json()["id"]

            # 2. Upload document to be ingested via Jina embeddings
            doc_content = (
                "PostgreSQL pgvector allows indexing high-dimensional embeddings. "
                "Jina embeddings provide dense semantic representations for document search."
            )
            files = {"file": ("jina_spec.txt", doc_content.encode("utf-8"), "text/plain")}
            upload_res = await client.post(
                "/api/v1/documents/upload",
                data={"knowledge_base_id": kb_id},
                files=files,
                headers=headers,
            )
            assert upload_res.status_code == 202
            doc_id = upload_res.json()["document"]["id"]

            # 3. Wait for background ingestion to complete
            import asyncio
            for _ in range(25):
                doc_chk = await client.get(f"/api/v1/documents/{doc_id}", headers=headers)
                if doc_chk.json().get("status") in ("completed", "failed"):
                    break
                await asyncio.sleep(0.5)

            final_doc = await client.get(f"/api/v1/documents/{doc_id}", headers=headers)
            assert final_doc.json().get("status") == "completed", f"Ingestion failed: {final_doc.json()}"

            # 4. Verify vector was stored in PostgreSQL document_chunks table with 1536 dimensions
            async with AsyncSessionLocal() as session:
                chunks_res = await session.execute(
                    select(DocumentChunk).where(DocumentChunk.document_id == doc_id)
                )
                chunks = chunks_res.scalars().all()
                assert len(chunks) > 0, "No chunks created in PostgreSQL"
                stored_chunk = chunks[0]
                assert stored_chunk.embedding is not None, "Chunk embedding must not be None"
                assert len(stored_chunk.embedding) == 1536, "Stored pgvector must have 1536 dimensions"

            # 5. Perform semantic search through Core API using real Jina query embedding
            search_res = await client.post(
                "/api/v1/search",
                json={
                    "knowledge_base_id": kb_id,
                    "query": "dense semantic representations for document search",
                    "top_k": 3,
                },
                headers=headers,
            )
            assert search_res.status_code == 200
            search_data = search_res.json()
            assert search_data["total"] > 0
            results = search_data["results"]
            assert len(results) > 0
            # Confirm cosine similarity score is a valid finite float between 0 and 1
            top_score = results[0]["similarity_score"]
            assert 0.0 <= top_score <= 1.0, f"Unexpected similarity score: {top_score}"
            assert "Jina embeddings" in results[0]["content"]

    finally:
        # Reset dependency overrides
        app.dependency_overrides.pop(get_settings, None)

        # 8. Clean up only records created by this test
        async with AsyncSessionLocal() as session:
            await session.execute(delete(Tenant).where(Tenant.id == tenant_id))
            await session.commit()


async def test_jina_error_handling_and_timeout():
    """Verify failure behavior when Jina returns error or invalid token."""
    # Test with invalid token (must fail explicitly, not silently fall back)
    bad_settings = Settings(
        embedding_base_url="https://api.jina.ai/v1",
        embedding_api_key="jina_invalid_token_test_1234567890",
        embedding_model="jina-embeddings-v4",
        embedding_dimensions=1536,
    )
    provider = OpenAIEmbeddingProvider(bad_settings)

    with pytest.raises(RuntimeError) as exc_info:
        await provider.get_embeddings(["Test failing call"])

    # Error message must be explicit and observable, without exposing secrets
    err_str = str(exc_info.value)
    assert "Embedding provider error" in err_str
    assert "jina_invalid_token_test_1234567890" not in err_str, "Secret must not be in error message"
